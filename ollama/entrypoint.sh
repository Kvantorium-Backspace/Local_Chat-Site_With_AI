#!/bin/bash

echo "🤖 Запуск Ollama сервера..."

# Запускаем Ollama в фоне
ollama serve &

# Ждем запуска
sleep 5

echo "📥 Загрузка моделей..."
echo "   - mistral:latest"
echo "   - minimax-m3:cloud"



# ─────────────────────────────────────────────────────────────────────────────
# Загружаем ваши модели
# ─────────────────────────────────────────────────────────────────────────────
ollama pull mistral:latest
ollama pull minimax-m3:cloud
# ─────────────────────────────────────────────────────────────────────────────
# Загружаем ваши модели
# ─────────────────────────────────────────────────────────────────────────────



echo "✅ Все модели загружены!"
echo "📋 Доступные модели:"
ollama list

# Оставляем процесс работающим
wait